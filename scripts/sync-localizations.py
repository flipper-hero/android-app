#!/usr/bin/env python3
"""Copy iOS translations into committed Android resources. Not needed to build."""
import argparse
import hashlib
import json
from pathlib import Path
import re
from xml.sax.saxutils import escape

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--ios", type=Path, required=True, help="Path to the iOS source checkout")
args = parser.parse_args()
root = Path(__file__).resolve().parents[1]
sources = ["App/Localizable.xcstrings", "Sources/AgentKit/Resources/Localizable.xcstrings",
           "Sources/FlipperKit/Resources/Localizable.xcstrings", "App/AppShortcuts.xcstrings"]
entries = {}
for source in sources:
    entries.update(json.loads((args.ios / source).read_text())["strings"])
languages = {"en": "values", "de": "values-de", "fr": "values-fr", "es": "values-es",
             "pt-BR": "values-pt-rBR", "it": "values-it", "ru": "values-ru", "uk": "values-uk",
             "pl": "values-pl", "tr": "values-tr", "ar": "values-ar", "hi": "values-hi",
             "zh-Hans": "values-zh-rCN", "ja": "values-ja", "ko": "values-ko"}
placeholder = re.compile(r"%(?:(\d+)\$)?(?:@|llu|lld|lu|ld|u|d|s)")


def android_text(text):
    position = 0

    def convert(match):
        nonlocal position
        position += 1
        return f"%{match.group(1) or position}$s"

    # Only genuine formatting strings need escaped literal percentage signs.
    if placeholder.search(text):
        # Consume %% atomically so a literal percent stays a single percent after formatting.
        text = re.sub(r"%%|%(?:(\d+)\$)?(?:@|llu|lld|lu|ld|u|d|s)|%",
                      lambda match: convert(match) if placeholder.fullmatch(match.group()) else "%%", text)
    else:
        text = text.replace("%%", "%")
    return '"' + escape(text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")) + '"'


keys = sorted(key for key in entries if key and "${" not in key)
ids = {key: "k" + hashlib.sha1(key.encode()).hexdigest()[:12] for key in keys}
full_only = re.compile(r"engagement|rpc_raw|badusb_execute|raw device|raw rpc|raw commands|gpio|marauder|hold to arm|scope note|export report|capabilities|run actions without prompts|Bad KB scripts start|Start the Bad KB script", re.I)
common_keys = [key for key in keys if not full_only.search(key)]
full_keys = [key for key in keys if full_only.search(key)]
for language, directory in languages.items():
    for flavor, selected_keys in [("main", common_keys), ("full", full_keys)]:
        lines = ['<?xml version="1.0" encoding="utf-8"?>', "<resources>"]
        for key in selected_keys:
            translations = entries[key].get("localizations", {})
            unit = translations.get(language, {}).get("stringUnit", {})
            text = unit.get("value", key)
            formatting = '' if placeholder.search(key) else ' formatted="false"'
            lines.append(f'    <string name="{ids[key]}"{formatting}>{android_text(text)}</string>')
        lines.append("</resources>")
        filename = "full-catalog.xml" if flavor == "full" else "catalog.xml"
        destination = root / f"app/src/{flavor}/res" / directory / filename
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_text("\n".join(lines) + "\n")

catalog = root / "app/src/main/kotlin/hero/flipper/app/Catalog.kt"
header = catalog.read_text().split("    private val ids:")[0]
mapping = [f"        {json.dumps(key, ensure_ascii=False)} to R.string.{ids[key]}," for key in common_keys]
catalog.write_text(header + "    private val ids: Map<String, Int> = mapOf(\n" + "\n".join(mapping) + "\n    ) + editionStringIds\n}\n")
for flavor in ["full", "play"]:
    mapping = [f"    {json.dumps(key, ensure_ascii=False)} to R.string.{ids[key]}," for key in full_keys] if flavor == "full" else []
    text = "package hero.flipper.app\n\n// Generated by scripts/sync-localizations.py\ninternal val editionStringIds: Map<String, Int> = "
    text += "mapOf(\n" + "\n".join(mapping) + "\n)\n" if mapping else "emptyMap()\n"
    (root / f"app/src/{flavor}/kotlin/hero/flipper/app/EditionStrings.kt").write_text(text)
print(f"Synced {len(common_keys)} common and {len(full_keys)} full-edition strings in {len(languages)} languages")
